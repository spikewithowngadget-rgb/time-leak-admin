function supported(value: string | null | undefined): value is Locale {
  return locales.some((locale) => locale.code === value);
}

export function getLocale(): Locale {
  if (sessionLocale) return sessionLocale;
  try {
    const stored = localStorage.getItem(storageKey);
    if (supported(stored)) return stored;
  } catch {
    /* Storage may be unavailable in private browsing. */
  }
  const browser =
    typeof navigator === "undefined" ? "en" : navigator.language.split("-")[0];
  return supported(browser) ? browser : "en";
}

export function setLocale(locale: string): void {
  const next = supported(locale) ? locale : "en";
  try {
    localStorage.setItem(storageKey, next);
  } catch {
    /* UI still changes for this page. */
  }
  activeLocale = next;
  sessionLocale = next;
  if (typeof document !== "undefined") {
    document.documentElement.lang = next;
    document.documentElement.dir = next === "ar" ? "rtl" : "ltr";
  }
  if (typeof window !== "undefined")
    window.dispatchEvent(new CustomEvent("tl:locale", { detail: next }));
}

let activeLocale = getLocale();
if (typeof document !== "undefined") {
  document.documentElement.lang = activeLocale;
  document.documentElement.dir = activeLocale === "ar" ? "rtl" : "ltr";
}

export function translate(key: string, params: TranslationParams = {}): string {
  const text = dictionaries[activeLocale][key] ?? en[key] ?? key;
  if (key === "noteSheet_days" && typeof params.count === "number") {
    const count = params.count;
    if (activeLocale === "ru") {
      const form = new Intl.PluralRules("ru").select(count);
      return `${count} ${form === "one" ? "день" : form === "few" ? "дня" : "дней"}`;
    }
    if (activeLocale === "en")
      return `${count} ${count === 1 ? "day" : "days"}`;
  }
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] === undefined ? match : String(params[name]),
  );
}

